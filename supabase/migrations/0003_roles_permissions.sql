drop policy if exists "acces utilisateurs actifs" on public.profiles;
create policy "profils lisibles" on public.profiles
  for select to authenticated using (public.is_active_user());
create policy "profils geres par users.manage" on public.profiles
  for update to authenticated
  using (public.has_permission('users.manage')) with check (public.has_permission('users.manage'));

alter table public.roles enable row level security;
alter table public.permissions enable row level security;
alter table public.role_permissions enable row level security;

create policy "roles lisibles" on public.roles for select to authenticated using (public.is_active_user());
create policy "roles geres" on public.roles for all to authenticated
  using (public.has_permission('roles.manage')) with check (public.has_permission('roles.manage'));
create policy "permissions lisibles" on public.permissions for select to authenticated using (public.is_active_user());
create policy "role_permissions lisibles" on public.role_permissions for select to authenticated using (public.is_active_user());
create policy "role_permissions geres" on public.role_permissions for all to authenticated
  using (public.has_permission('roles.manage')) with check (public.has_permission('roles.manage'));
