create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', new.email), new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

-- 6. Fonctions de contrôle des droits
create or replace function public.has_permission(p_code text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    join public.roles r on r.code = p.role
    where p.id = auth.uid()
      and p.is_active
      and (r.is_super
           or exists (select 1 from public.role_permissions rp
                      where rp.role_code = p.role and rp.permission_code = p_code))
  );
$$;

create or replace function public.my_permissions()
returns setof text
language sql
stable
security definer
set search_path = public
as $$
  select perm.code
  from public.profiles p
  join public.roles r on r.code = p.role
  join public.permissions perm
    on r.is_super
    or exists (select 1 from public.role_permissions rp
               where rp.role_code = p.role and rp.permission_code = perm.code)
  where p.id = auth.uid() and p.is_active;
$$;

-- Liste des utilisateurs avec la date de dernière connexion (stockée dans auth.users)
create or replace function public.list_users()
returns table (
  id uuid, full_name text, email text, phone text, job_title text, role text,
  is_active boolean, created_at timestamptz, last_sign_in_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.full_name, coalesce(p.email, u.email), p.phone, p.job_title, p.role,
         p.is_active, coalesce(u.created_at, p.created_at), u.last_sign_in_at
  from public.profiles p
  left join auth.users u on u.id = p.id
  where public.is_active_user()
  order by p.full_name;
$$;

